  function startLivePreview(hero) {
    const video = getActiveVideo();
    const canvas = hero && hero.querySelector('.cdl-hero-live');
    if (!video || !canvas) return null;
    const ctx = canvas.getContext('2d');
    if (!ctx) return null;
    let raf = 0, shown = false, failed = false;
    function frame() {
      if (failed) return;
      try {
        const vw = video.videoWidth, vh = video.videoHeight;
        if (vw && vh) {
          if (canvas.width !== vw || canvas.height !== vh) { canvas.width = vw; canvas.height = vh; }
          ctx.drawImage(video, 0, 0, vw, vh);
          if (!shown) {

            try { ctx.getImageData(0, 0, 1, 1); } catch (e) { failed = true; canvas.hidden = true; return; }
            canvas.hidden = false;
            const im = hero.querySelector('.cdl-hero-img');
            if (im) im.style.opacity = '0';
            shown = true;
          }
        }
      } catch (e) { failed = true; canvas.hidden = true; return; }
      raf = requestAnimationFrame(frame);
    }
    raf = requestAnimationFrame(frame);
    return () => { failed = true; if (raf) cancelAnimationFrame(raf); };
  }

