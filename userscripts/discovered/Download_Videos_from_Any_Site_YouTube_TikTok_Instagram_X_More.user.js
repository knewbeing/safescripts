  function triggerDownload() {
    let pageUrl = location.href;
    if (isTikTok() || isInstagram() || isFacebook() || isTwitter()) {
      const found = getTargetUrl();
      if (found) pageUrl = found;
      else { toast(t('novideo')); return; }
    }
    if (isSpotify()) {
      const sp = getSpotifyTrackUrl();
      if (sp) pageUrl = sp;
      else { toast(t('notrack')); return; }
    }
    if (isExtraSite()) {
      const found = resolveExtraSiteUrl();
      if (found) pageUrl = found;
    }
    if (appDownloadAllowed()) showChoice(pageUrl);
    else openWebsiteDownloader(pageUrl);
  }

