  function placeFloatButton() {
    const btn = ensureFloatButton();
    const v = getActiveVideo();
    if (!v) { btn.style.display = 'none'; return; }
    const r = v.getBoundingClientRect();
    if (r.width < 120 || r.height < 90 || r.bottom < 60 || r.top > window.innerHeight - 60) {
      btn.style.display = 'none'; return;
    }
    btn.style.display = 'flex';
    let left = r.right - 40 - 12;
    let top = r.bottom - 40 - 12;
    left = Math.max(8, Math.min(left, window.innerWidth - 48));
    top = Math.max(8, Math.min(top, window.innerHeight - 48));
    btn.style.left = left + 'px';
    btn.style.top = top + 'px';
  }

