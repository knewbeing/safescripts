  function openInApp(pageUrl) {
    const link = APP_PROTOCOL + encodeURIComponent(pageUrl);
    let launched = false;
    const onBlur = () => { launched = true; };
    window.addEventListener('blur', onBlur, { once: true });
    try { location.href = link; } catch (e) {}
    setTimeout(() => {
      window.removeEventListener('blur', onBlur);
      if (!launched && !document.hidden) showGetAppPrompt();
    }, 1600);
  }

  function mountModal(backdrop, actions, rerender, onClose) {
    document.body.appendChild(backdrop);
    requestAnimationFrame(() => backdrop.classList.add('show'));
    function cleanup() { if (typeof onClose === 'function') { try { onClose(); } catch (e) {} } }
    function close() {
      backdrop.classList.remove('show');
      document.removeEventListener('keydown', onKey);
      cleanup();
      setTimeout(() => backdrop.remove(), 200);
    }
    function onKey(e) {
      if (e.key === 'Escape') { e.preventDefault(); close(); }
    }
    document.addEventListener('keydown', onKey);

    const primary = backdrop.querySelector('.cdl-line-primary');
    if (primary) { try { primary.focus({ preventScroll: true }); } catch (e) { primary.focus(); } }
    const sel = backdrop.querySelector('[data-langsel]');
    if (sel) {
      sel.addEventListener('change', e => {
        setLang(e.target.value);
        if (typeof rerender === 'function') {
          document.removeEventListener('keydown', onKey);
          cleanup();
          backdrop.remove();
          rerender();
        }
      });
      sel.addEventListener('click', e => e.stopPropagation());
    }
    backdrop.addEventListener('click', e => {
      if (e.target === backdrop) { close(); return; }
      const btn = e.target.closest('[data-act]');
      if (!btn) return;
      const act = btn.getAttribute('data-act');
      close();
      if (act === 'cancel') return;
      if (actions && actions[act]) actions[act]();
    });
  }

